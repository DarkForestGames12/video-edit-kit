"""Stage 8 - keep every finished edit as a worked example, so the next edit can learn from it.

  python -m vek example <job> <slug> "Title"
      -> examples/<slug>/edit.json   the edit as rendered (a one-off brand is copied next to it)
         examples/<slug>/cutlog.md   generated: playback order with the words kept, everything
                                     removed from the source (with what was said there), graphics
                                     timeline with the word each one lands on
         examples/<slug>/NOTES.md    skeleton for Claude to fill in: the video, key decisions,
                                     problems and fixes, lessons (never overwritten once it exists)
  python -m vek example-pack <slug>
      -> checks NOTES.md is filled in, rebuilds examples/README.md (the index), zips for upload:
         example-<slug>.zip if only examples/ changed, else the whole kit as video-edit-kit.zip
  python -m vek pack-kit
      -> the whole kit (tracked + new files, .gitignore respected) as video-edit-kit.zip

Text only: no frames, audio or video leave the job folder (the repo is public).
"""
import datetime, json, os, re, shutil, subprocess, zipfile
from .common import Job, Timeline, REPO

EX = os.path.join(REPO, "examples")
OUT = "/mnt/user-data/outputs"
SLUG = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def fmt(t):
    t = float(t)
    return f"{int(t // 60)}:{t % 60:05.2f}" if t >= 60 else f"{t:.2f}"


def _word_at(words, t):
    """Caption word playing at output time t (index, text)."""
    best = None
    for w in words:
        if w["t"] <= t + 0.08:
            best = w
        else:
            break
    return (best["i"], best["w"]) if best else (None, "")


def _gaps(segs, total):
    iv = sorted((s["vin"], s["vout"]) for s in segs)
    out, cur = [], 0.0
    for a, b in iv:
        if a > cur + 0.04:
            out.append((cur, a))
        cur = max(cur, b)
    if total > cur + 0.04:
        out.append((cur, total))
    return out


def _phrase_label(p, a, b):
    ov = min(b, p["e"]) - max(a, p["s"])
    part = "" if (p["s"] >= a - 0.03 and p["e"] <= b + 0.03) else " (part)"
    txt = p.get("text", "").strip()
    ctx = p.get("ctx", "").strip()
    lab = f'"{txt}"' if txt else "(no words)"
    if ctx and ctx.lower().strip(".?!, ") != txt.lower().strip(".?!, "):
        lab += f' (ctx "{ctx}")'
    fl = [f for f in p.get("flags", []) if not f.startswith("pause")]
    if fl:
        lab += " [" + ", ".join(fl) + "]"
    return lab + part, ov


def cutlog(job, ed, title):
    edl = job.load("edl.json"); words = job.load("words.json", [])
    ph = job.load("phrases.json", {}).get("phrases", [])
    probe = job.load("probe.json", {})
    tl = Timeline(edl, words, ed)
    segs = edl["segs"]; src = probe.get("duration", max(s["vout"] for s in segs))
    fix = {int(k): v for k, v in ed.get("captions", {}).get("fix", {}).items()}
    wtext = lambda w: fix.get(w["i"], w["w"])
    notes = {s["name"]: s.get("note", "") for s in ed["segments"]}
    L = [f"# Cut log: {title}", "",
         f"Generated by `python -m vek example`. Source {src:.1f} s -> output {edl['total']:.1f} s, "
         f"{len(segs)} segments, format {ed.get('format', '16:9')}, mode {ed.get('mode', 'full')}. "
         "`src` = source seconds (video clock), `out` = output seconds, `w12` = caption word index.", ""]
    try:
        from .mix import loudness
        if job.has("master.wav"):
            I, P = loudness(job.p("master.wav"))
            L += [f"Master loudness {I} LUFS, true peak {P} dBTP.", ""]
    except Exception:
        pass

    L += ["## Playback order", ""]
    for k, s in enumerate(segs):
        ws = [w for w in words if w.get("seg") == s["name"]]
        later_earlier = any(o["vin"] < s["vin"] - 0.05 for o in segs[k + 1:])
        rep = [o["name"] for o in segs if o is not s and min(o["vout"], s["vout"]) - max(o["vin"], s["vin"]) > 0.1]
        z = s["shot"].get("z") or [1, 1]
        tags = []
        if later_earlier: tags.append("moved earlier than its place in the source")
        if rep: tags.append("same source as " + ", ".join(rep))
        wr = f" · w{ws[0]['i']}-w{ws[-1]['i']}" if ws else ""
        L.append(f"{k + 1}. **{s['name']}** · out {fmt(s['ostart'])}-{fmt(s['oend'])} · src {fmt(s['vin'])}-{fmt(s['vout'])}"
                 f" · {s['enter']} · z {z[0]}->{z[-1]}{wr}" + (f" · *{notes.get(s['name'])}*" if notes.get(s['name']) else ""))
        if tags: L.append(f"   - {'; '.join(tags)}")
        if ws: L.append("   > " + " ".join(wtext(w) for w in ws))
    if edl.get("endcard_in") is not None:
        L.append(f"{len(segs) + 1}. **END CARD** · out {fmt(edl['endcard_in'])}-{fmt(edl['total'])}")
    L.append("")

    L += ["## Removed from the source", ""]
    total_cut = 0.0
    for a, b in _gaps(segs, src):
        total_cut += b - a
        items = []
        for p in ph:
            lab, ov = _phrase_label(p, a, b)
            if ov > 0.06:
                items.append(lab)
        what = "; ".join(items) if items else "silence / pause"
        if a < 0.05: what = "lead-in: " + what
        if b > src - 0.05: what = "tail: " + what
        L.append(f"- src {fmt(a)}-{fmt(b)} ({b - a:.2f} s): {what}")
    L += ["", f"Total removed: {total_cut:.1f} s of {src:.1f} s.", ""]

    L += ["## Graphics timeline", ""]
    def at(ref):
        t = tl.t(ref); i, w = _word_at(words, t)
        return f"{fmt(t)}" + (f' (on w{i} "{fix.get(i, w)}")' if i is not None else "")
    ht = ed.get("hook_text")
    if ht: L.append(f"- hook_text {' / '.join(ht.get('lines', []))}: {at(ht.get('in', 0.06))} -> {fmt(tl.t(ht.get('out')))}"
                    + (f", tuck {ht['tuck']}" if "tuck" in ht else ""))
    tc = ed.get("title_card")
    if tc: L.append(f"- title_card \"{tc.get('kicker', '')} | {tc.get('title', '')} | {tc.get('sub', '')}\": "
                    f"{at(tc['in'])} -> out {fmt(tl.t(tc['out']))} -> end {fmt(tl.t(tc['end']))}")
    for p in ed.get("punches", []):
        L.append(f"- punch z {p.get('z', 1.3)}: {at(p['at'])}")
    for st in ed.get("stickers", []):
        L.append(f"- sticker {st['icon']} ({st.get('side', 'right')}, {st.get('mode', 'pop')}): {at(st['in'])} -> {fmt(tl.t(st['out']))}")
    for c in ed.get("cards", []):
        extra = ""
        if c.get("pop") is not None: extra = f", pop {at(c['pop'])}"
        if c.get("beats"): extra = ", beats " + ", ".join(at(b) for b in c["beats"])
        L.append(f"- card {c.get('kind', 'plain')} \"{c.get('label', '')}\" ({c.get('icon', '')}, {c.get('color', '')}): "
                 f"{at(c['in'])} -> {fmt(tl.t(c['out']))}{extra}")
    b = ed.get("burst")
    if b: L.append(f"- burst {', '.join(i[0] for i in b.get('icons', []))}: {at(b['in'])} -> {fmt(tl.t(b['out']))}")
    ec = ed.get("end_card")
    if ec:
        try:
            from .common import load_brand
            ec = {**load_brand(ed["brand"]).get("end_card", {}), **ec}
        except Exception:
            pass
        L.append(f"- end_card {' / '.join(ec.get('lines') or ['(brand lines)'])}, button {ec.get('button') or 'none'}, "
                    f"loop src {ec.get('loop')}, {ec.get('length', '')} s")
    cap = ed.get("captions", {})
    if cap:
        bits = []
        if cap.get("keywords"): bits.append("keywords " + ", ".join(f"{k}={v}" for k, v in cap["keywords"].items()))
        if fix: bits.append("fix " + ", ".join(f"w{k}->{v}" for k, v in fix.items()))
        if cap.get("groups"): bits.append(f"{len(cap['groups'])} hand-set lines")
        if cap.get("skip"): bits.append(f"skip {cap['skip']}")
        L.append("- captions: " + "; ".join(bits))
    if ed.get("music"): L.append(f"- music: {json.dumps(ed['music'])}")
    if ed.get("mix"): L.append(f"- mix overrides: {json.dumps(ed['mix'])}")
    for c in ed.get("sfx_extra", []):
        L.append(f"- sfx {c['kind']}: {at(c['t'])}")
    return "\n".join(L) + "\n"


NOTES = """# {title}

Source {src} s ({w}x{h}) -> {out} s, {fmt_} {mode} render. Brand: {brand}. Edited {date}.
Tags: TODO comma-separated (speaker style, camera, structure, techniques), e.g. webcam, fast talker, pros/cons, cold open

## The video
TODO: topic, who is speaking and how (pace, fillers, energy), camera and setting, visual problems seen on the contact sheets.

## Key decisions
TODO: the hook and why it won; the structure; what was cut and why; graphics choices (cards, stickers, burst) and the words they sit on; anything deliberately kept.

## Problems and fixes
TODO: what went wrong during this edit (mishearings, overlaps, levels, renders) and what fixed it, including any change made to the kit.

## Lessons for next time
TODO: short, reusable rules this video taught.
"""


def make(job_dir, slug, title=None):
    if not SLUG.match(slug):
        raise SystemExit("slug must be lowercase words joined by hyphens, e.g. getting-to-know-others")
    job = Job(job_dir); ed = job.load("edit.json"); edl = job.load("edl.json"); probe = job.load("probe.json", {})
    title = title or slug.replace("-", " ").title()
    d = os.path.join(EX, slug); os.makedirs(d, exist_ok=True)
    ed = json.loads(json.dumps(ed))
    brand = ed.get("brand", "")
    bpath = brand if os.path.isabs(brand) else job.p(brand)
    if brand and os.path.isfile(bpath):
        shutil.copy(bpath, os.path.join(d, "brand.json"))
        ed["brand"] = f"examples/{slug}/brand.json"
        bdesc = "one-off (brand.json in this folder)"
    else:
        bdesc = f"channel kit `{brand}`"
    src = probe.get("duration", 0); out = edl["total"]
    ed["notes"] = (f"Worked example: {title} ({src:.1f} s -> {out:.1f} s). Read NOTES.md first; cutlog.md shows "
                   "what was kept, cut and where every graphic lands. Times: segment in/out = source video seconds; "
                   "everything else = output seconds or refs (w12, B1.start, title.in, end).")
    date = datetime.date.today().isoformat()
    try:   # re-running keeps the original date
        date = json.load(open(os.path.join(d, "edit.json")))["example"]["date"]
    except Exception:
        pass
    ed["example"] = {"title": title, "source_s": round(src, 2), "output_s": round(out, 2), "date": date}
    keys = ["brand", "format", "mode", "notes", "example"]
    ed = {**{k: ed[k] for k in keys if k in ed}, **{k: v for k, v in ed.items() if k not in keys}}
    with open(os.path.join(d, "edit.json"), "w") as f:
        json.dump(ed, f, indent=1, ensure_ascii=False)
    with open(os.path.join(d, "cutlog.md"), "w") as f:
        f.write(cutlog(job, ed, title))
    np_ = os.path.join(d, "NOTES.md")
    if not os.path.exists(np_):
        with open(np_, "w") as f:
            f.write(NOTES.format(title=title, src=f"{src:.1f}", out=f"{out:.1f}", w=probe.get("width", "?"),
                                 h=probe.get("height", "?"), fmt_=ed.get("format", "16:9"), mode=ed.get("mode", "full"),
                                 brand=bdesc, date=date))
        print(f"[example] wrote {np_} - fill in every TODO (python -m vek example-pack {slug} checks)")
    else:
        print(f"[example] kept existing {np_}")
    index()
    print(f"[example] examples/{slug}/: edit.json, cutlog.md, NOTES.md" + (", brand.json" if "one-off" in bdesc else ""))


def index():
    rows = []
    for s in sorted(os.listdir(EX)):
        d = os.path.join(EX, s)
        if not os.path.isdir(d) or not os.path.exists(os.path.join(d, "edit.json")):
            continue
        ed = json.load(open(os.path.join(d, "edit.json")))
        meta = ed.get("example", {})
        title, tags = meta.get("title", s), ""
        if os.path.exists(os.path.join(d, "NOTES.md")):
            txt = open(os.path.join(d, "NOTES.md")).read()
            m = re.search(r"^# (.+)$", txt, re.M); title = m.group(1).strip() if m else title
            m = re.search(r"^Tags:\s*(.+)$", txt, re.M); tags = m.group(1).strip() if m else ""
            if tags.startswith("TODO"): tags = ""
        hm = lambda t: f"{t:.1f} s" if t < 120 else f"{int(t // 60)}:{int(t % 60):02d}"
        dur = f"{hm(meta['source_s'])} -> {hm(meta['output_s'])}" if meta else ""
        rows.append((meta.get("date", ""), s, title, dur, ed.get("format", ""), tags))
    rows.sort()
    L = ["# Worked examples", "",
         "One folder per finished edit, oldest first. Before editing a new video, skim this table, then read",
         "`NOTES.md` of the one or two closest examples (same channel, similar speaker, length or structure).",
         "Open `cutlog.md` / `edit.json` when you need a concrete pattern: what got cut, how lines were",
         "grouped, which word each graphic sits on. Add a folder after every edit (`python -m vek example`).", "",
         "| example | title | source -> output | format | tags |", "|---|---|---|---|---|"]
    for date, s, title, dur, fmt_, tags in rows:
        L.append(f"| [{s}]({s}/NOTES.md) | {title} | {dur} | {fmt_} | {tags} |")
    with open(os.path.join(EX, "README.md"), "w") as f:
        f.write("\n".join(L) + "\n")


def _kit_files():
    try:
        r = subprocess.run(["git", "ls-files", "-co", "--exclude-standard"], cwd=REPO, capture_output=True, text=True, check=True)
        files = [f for f in r.stdout.splitlines() if os.path.isfile(os.path.join(REPO, f))]
        if files:
            return sorted(set(files))
    except Exception:
        pass
    skip = re.compile(r"(^|/)(\.git|__pycache__|jobs)(/|$)|\.(pyc|mp4|mov|wav)$")
    out = []
    for root, dirs, fs in os.walk(REPO):
        for f in fs:
            rel = os.path.relpath(os.path.join(root, f), REPO)
            if not skip.search(rel):
                out.append(rel)
    return sorted(out)


def _kit_changed():
    """True if anything outside examples/ differs from the clone (or this isn't a git clone)."""
    try:
        r = subprocess.run(["git", "status", "--porcelain"], cwd=REPO, capture_output=True, text=True, check=True)
    except Exception:
        return True
    return any(not l[3:].strip('"').startswith("examples/") for l in r.stdout.splitlines() if l.strip())


def pack_kit():
    os.makedirs(OUT, exist_ok=True)
    z = os.path.join(OUT, "video-edit-kit.zip")
    with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in _kit_files():
            zf.write(os.path.join(REPO, f), f)
    print(f"[pack] {z} ({os.path.getsize(z) // 1024} KB) - the whole kit, examples included.\n"
          "        Upload: unzip, then on github.com open the repo -> Add file -> Upload files -> drag in\n"
          "        everything from the unzipped folder (same-named files are replaced).")
    return z


def pack(slug):
    d = os.path.join(EX, slug)
    if not os.path.exists(os.path.join(d, "NOTES.md")):
        raise SystemExit(f"no examples/{slug}/NOTES.md - run: python -m vek example <job> {slug} \"Title\"")
    txt = open(os.path.join(d, "NOTES.md")).read()
    todo = [l for l in txt.splitlines() if "TODO" in l]
    if todo:
        raise SystemExit("NOTES.md still has TODOs - fill them in first:\n  " + "\n  ".join(todo))
    index()
    if _kit_changed():
        print("[pack] the kit itself changed during this edit -> packing the whole kit")
        return pack_kit()
    os.makedirs(OUT, exist_ok=True)
    z = os.path.join(OUT, f"example-{slug}.zip")
    with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in sorted(os.listdir(d)):
            zf.write(os.path.join(d, f), f"examples/{slug}/{f}")
        zf.write(os.path.join(EX, "README.md"), "examples/README.md")
    print(f"[pack] {z} ({os.path.getsize(z) // 1024} KB).\n"
          "        Upload: unzip, then on github.com open the repo -> Add file -> Upload files -> drag in the\n"
          "        'examples' folder (it merges into the existing one; examples/README.md is replaced).")
    return z
